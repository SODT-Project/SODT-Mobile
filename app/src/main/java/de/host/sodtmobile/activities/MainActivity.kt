package de.host.sodtmobile.activities

import android.content.Intent
import android.os.Bundle
import android.util.Log
import android.view.Menu
import android.view.MenuItem
import android.view.View
import android.widget.TextView
import android.widget.Toast
import androidx.activity.enableEdgeToEdge
import androidx.appcompat.app.AppCompatActivity
import androidx.core.view.ViewCompat
import androidx.core.view.WindowInsetsCompat
import androidx.preference.PreferenceManager.getDefaultSharedPreferences
import de.host.sodtmobile.R

class MainActivity : AppCompatActivity() {
    private lateinit var serverTextView: TextView
    private lateinit var portTextView: TextView
    override fun onCreate(savedInstanceState: Bundle?) {
        // generated by default
        super.onCreate(savedInstanceState)
        enableEdgeToEdge()
        setContentView(R.layout.activity_main)
        ViewCompat.setOnApplyWindowInsetsListener(findViewById(R.id.main)) { v, insets ->
            val systemBars = insets.getInsets(WindowInsetsCompat.Type.systemBars())
            v.setPadding(systemBars.left, systemBars.top, systemBars.right, systemBars.bottom)
            insets
        }
        // set toolbar as support action bar
        setSupportActionBar(findViewById(R.id.toolbar))
        serverTextView = findViewById(R.id.textView_currentServer)
        portTextView = findViewById(R.id.textView_currentPort)
        // Set the text for server and port from preferences
        val address = getString(R.string.selected_server, getDefaultSharedPreferences(this).getString("preference_server_address", "not set"))
        val port = getString(R.string.selected_port, getDefaultSharedPreferences(this).getString("preference_server_port", "not set"))
        serverTextView.text = address
        portTextView.text = port

    }
    // needed for mysterious preferences bug
    private fun checkIfPreferencesSet(): Boolean {
        // initialize sodt client null checks are necessary because of mystic preferences bug
        val address = getDefaultSharedPreferences(this).getString("preference_server_address",null)
        if (address == null) {
            Log.e("ConnectedActivity", "Server address is not set in preferences")
            Toast.makeText(this, "Server address is not set in preferences", Toast.LENGTH_LONG).show()
            return false
        }
        val publicKey = getDefaultSharedPreferences(this).getString("preference_server_public_key", null)
        if (publicKey == null) {
            Log.e("ConnectedActivity", "Server public key is not set in preferences")
            Toast.makeText(this, "Server public key is not set in preferences", Toast.LENGTH_LONG).show()
            return false
        }
        val portString = getDefaultSharedPreferences(this).getString("preference_server_port", "0")
        val port = portString?.toIntOrNull()
        if (port == null || port <= 0) {
            Log.e("ConnectedActivity", "Invalid server port in preferences: $portString")
            Toast.makeText(this, "Invalid server port in preferences", Toast.LENGTH_LONG).show()
            return false
        }
        return true
    }

    override fun onCreateOptionsMenu(menu: Menu?): Boolean {
        // Inflate the menu; this adds items to the action bar if it is present.
        menuInflater.inflate(R.menu.menu_actions, menu)
        return super.onCreateOptionsMenu(menu)
    }

    override fun onOptionsItemSelected(item: MenuItem): Boolean {
        when (item.itemId) {
            R.id.menu_item_preferences -> {
                // Open settings activity
                startActivity(Intent(this, PreferencesActivity::class.java))
                return true
            }
            R.id.menu_item_logs -> {
                // Open connect activity
                startActivity(Intent(this, LogsActivity::class.java))
                return true
            }
        }
        return super.onOptionsItemSelected(item)
    }
    fun onConnectButtonClick(view: View) {
        if (!checkIfPreferencesSet()) {
            // If preferences are not set, do not proceed
            return
        }
        val intent = Intent(this, ConnectedActivity::class.java)
        intent.putExtra("serverAddress", getDefaultSharedPreferences(this).getString("preference_server_address", "not set"))
        intent.putExtra("serverPort", getDefaultSharedPreferences(this).getString("preference_server_port", "0")?.toInt() ?: 0)
        intent.putExtra("publicKey", getDefaultSharedPreferences(this).getString("preference_server_public_key", null))
        startActivity(intent)
    }

    override fun onResume() {
        super.onResume()
        val address = getString(R.string.selected_server, getDefaultSharedPreferences(this).getString("preference_server_address", "not set"))
        val port = getString(R.string.selected_port, getDefaultSharedPreferences(this).getString("preference_server_port", "not set"))
        serverTextView.text = address
        portTextView.text = port
    }
}